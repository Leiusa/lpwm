#!/usr/bin/env python
"""
Short single-GPU training comparison run THROUGH train_dlp.py (the real training entry), for three paths:

  reference   stn_backend=reference, fused_composite=False   (the previous behaviour)
  triton      stn_backend=triton,    fused_composite=False   (Triton crop/paste)
  fused       stn_backend=triton,    fused_composite=True    (Triton crop + fused paste/composite)

Every path uses the same config, seed (initial weights, data order, sampling noise) and loss configuration;
the base config decides those (its recon_loss_type is used as is: a vgg config is trained with vgg on all
paths). Each path is run twice, in opposite orders, so the trajectory divergence BETWEEN paths can be read
against the divergence between two runs of the SAME path (atomics make runs non-bitwise-repeatable).

What it records per run: the startup path line, the first-step check, per-epoch train loss / reconstruction /
PSNR, step time (CUDA events around forward+backward+update), peak allocated memory, epoch wall time and the
validation loss written by train_dlp.py. After training, one fixed batch of validation images is reconstructed
by every final checkpoint (all evaluated on the reference path, so only the trained weights differ), and a
side-by-side image grid is saved for visual inspection.

If the dataset is `shapes` (procedurally generated by skimage) it is generated once, deterministically, and
shared by all runs; it is synthetic data, not a real dataset. Short training says nothing about convergence.

    python train_dlp_compare.py --repo-root <repo> --config configs/shapes.json --epochs 3 --out <dir>
"""

import argparse
import contextlib
import importlib
import json
import os
import re
import shutil
import socket
import sys
import time

import torch

_HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, _HERE)

import bench_e2e as be  # noqa: E402

PATHS = {"reference": dict(stn_backend="reference", fused_composite=False),
         "triton": dict(stn_backend="triton", fused_composite=False),
         "fused": dict(stn_backend="triton", fused_composite=True)}
ORDERS = (("reference", "triton", "fused"), ("fused", "triton", "reference"))


def patch_shapes_dataset(seed):
    """Deterministic, cached `shapes` dataset (the stock generator is unseeded). Only used by this driver."""
    import datasets.get_dataset as gd
    import datasets.shapes_ds as sd
    from skimage.draw import random_shapes as stock
    original = sd.generate_shape_dataset_torch
    cache = {}

    def deterministic(img_size=64, num_images=10_000, **kw):
        key = (img_size, num_images)
        if key not in cache:
            counter = [0]

            def seeded(*a, **k):
                counter[0] += 1
                k["rng"] = 1_000_003 * seed + 10_007 * num_images + counter[0]
                return stock(*a, **k)

            sd.random_shapes = seeded
            try:
                cache[key] = original(img_size=img_size, num_images=num_images, **kw)
            finally:
                sd.random_shapes = stock
        return cache[key]

    gd.generate_shape_dataset_torch = deterministic


def parse_log(log_dir):
    text = open(os.path.join(log_dir, "log.txt")).read()
    rec = {"log_dir": log_dir}
    m = re.search(r"STN backend: (\S+) \| fused_composite: (\S+) \| seed: (\S+).*?init_weights_sha256: (\w+)", text)
    if m:
        rec["startup"] = {"stn_backend": m.group(1), "fused_composite": m.group(2), "seed": m.group(3), "init_weights_sha256": m.group(4)}
    m = re.search(r"path check \(first step\) ok: backend=(\S+), fused_composite_calls=(\d+), first_batch_sha256=(\w+), first_step_loss=([\d.eE+-]+)", text)
    if m:
        rec["first_step"] = {"backend": m.group(1), "fused_composite_calls": int(m.group(2)), "first_batch_sha256": m.group(3),
                             "first_step_loss": float(m.group(4))}
    # log_line() does not add newlines, so an entry can follow other text on the same line: match anywhere
    rec["epochs"] = [{k: float(v) for k, v in re.findall(r"(\w+)=([\d.eE+-]+)", entry)}
                     for entry in re.findall(r"\[step-timing\]([^\[\n]*)", text)]
    rec["validation_loss"] = [float(v) for v in re.findall(r"^validation loss: ([\d.eE+-]+)", text, flags=re.M)]
    return rec


def train_one(repo_root, base_cfg, path, tag, out, args):
    cfg = dict(base_cfg)
    cfg.update(PATHS[path])
    cfg.update(seed=args.seed, num_epochs=args.epochs, log_step_timing=True, eval_im_metrics=False, run_prefix=f"_{path}{tag}")
    cfg.update(args.set)
    cfg_path = os.path.join(out, f"cfg_{path}{tag}.json")
    json.dump(cfg, open(cfg_path, "w"), indent=1)
    before = set(os.listdir(out))
    T = importlib.import_module("train_dlp")
    t0 = time.perf_counter()
    with open(os.path.join(out, f"stdout_{path}{tag}.log"), "w") as fh, contextlib.redirect_stdout(fh), contextlib.redirect_stderr(fh):
        T.train_dlp(cfg_path)
    new = sorted(d for d in set(os.listdir(out)) - before if d.endswith(f"_gdlp_{path}{tag}"))
    rec = parse_log(os.path.join(out, new[-1]))
    rec.update(path=path, tag=tag, cfg_path=cfg_path, total_wall_s=time.perf_counter() - t0)
    print(f"  {path}{tag}: {len(rec['epochs'])} epochs in {rec['total_wall_s']:.0f}s; startup={rec.get('startup')}; first_step={rec.get('first_step')}", flush=True)
    return rec


def fixed_validation_batch(ds, n):
    """n validation images at fixed positions, spread over as many different episodes as possible.

    A sequence dataset with `seq_per_episode` (BAIR) is sampled at evenly spaced episodes and a varying
    frame offset; any other dataset (shapes) simply uses its first n items. A length-1 time axis
    ([n, 1, C, H, W]) is dropped so the result is a plain 4-D image batch [n, C, H, W].
    """
    seq = getattr(ds, "seq_per_episode", None)
    if seq:
        n_eps = len(ds) // seq
        idx = [round(i * (n_eps - 1) / max(n - 1, 1)) * seq + (7 * i) % seq for i in range(n)]
    else:
        idx = list(range(n))
    x = torch.stack([ds[i][0] for i in idx])
    return x.reshape(-1, *x.shape[-3:])[:n], idx


def reconstruct(model, x4):
    model.eval()
    with torch.no_grad():
        out = model(x4.unsqueeze(1), deterministic=True, with_loss=False)["rec_rgb"]
    return out.reshape(x4.shape).clamp(0, 1)


def load_final_model(run, out):
    """Rebuild the model of a finished run and load its final checkpoint (evaluated on the reference path)."""
    from build_model import build
    cfg = json.load(open(run["cfg_path"]))
    cfg["fused_composite"] = False
    tmp = os.path.join(out, f"recon_cfg_{run['path']}{run['tag']}.json")
    json.dump(cfg, open(tmp, "w"))
    model, _, _ = build(tmp, "cuda")
    ckpt = os.path.join(run["log_dir"], "saves", f"{cfg['ds']}_gdlp{cfg['run_prefix']}.pth")
    model.load_state_dict(torch.load(ckpt, map_location="cuda", weights_only=False))
    return model


def full_validation_metrics(model, ds, batch_size=16):
    """MSE / PSNR over the WHOLE validation set (deterministic pass, reference path)."""
    loader = torch.utils.data.DataLoader(ds, batch_size=batch_size, shuffle=False, num_workers=4)
    sq, n = 0.0, 0
    for batch in loader:
        x4 = batch[0].cuda().reshape(-1, *batch[0].shape[-3:])
        sq += float(((reconstruct(model, x4) - x4.clamp(0, 1)) ** 2).sum())
        n += x4.numel()
    mse = sq / n
    return {"images": len(ds), "mse": mse, "psnr_db": float(-10 * torch.log10(torch.tensor(mse)))}


def save_grid(rows, path, nrow):
    import torchvision.utils as vutils
    vutils.save_image(torch.cat([r.cpu().clamp(0, 1) for r in rows]), path, nrow=nrow, pad_value=1)


def reconstruction_check(repo_root, base_cfg, runs, out, args):
    """Reconstruct fixed validation images with every final checkpoint, all on the reference path, and
    measure MSE/PSNR on that batch and on the whole validation set. The grid uses pass 1 only."""
    import lpwm_stn
    from datasets.get_dataset import get_image_dataset
    ds = get_image_dataset(base_cfg["ds"], base_cfg["root"], mode="valid", image_size=base_cfg["image_size"])
    x4, idx = fixed_validation_batch(ds, args.recon_images)
    x4 = x4.cuda()
    lpwm_stn.set_backend("reference")
    res, recs, weights = {"fixed_batch_dataset_indices": idx, "runs": {}}, {}, {}
    for r in runs:
        model = load_final_model(r, out)
        rec = reconstruct(model, x4)
        key = r["path"] + r["tag"]
        mse = float(((rec - x4.clamp(0, 1)) ** 2).mean())
        res["runs"][key] = {"fixed_batch": {"mse": mse, "psnr_db": float(-10 * torch.log10(torch.tensor(mse))), "finite": bool(torch.isfinite(rec).all())},
                            "full_validation_set": full_validation_metrics(model, ds)}
        if r["tag"] == "_p1":
            recs[r["path"]] = rec.cpu()
            weights[r["path"]] = torch.cat([p.detach().flatten().double().cpu() for p in model.parameters()])
        del model
        torch.cuda.empty_cache()
    order = [p for p in PATHS if p in recs]
    save_grid([x4] + [recs[p] for p in order], os.path.join(out, "reconstructions.png"), nrow=x4.shape[0])
    res["grid_rows"] = ["target"] + order
    res["weight_relative_l2_between_final_models"] = {
        f"{a}_vs_{b}": float(torch.linalg.vector_norm(weights[a] - weights[b]) / torch.linalg.vector_norm(weights[b]))
        for a, b in (("triton", "reference"), ("fused", "reference"), ("fused", "triton")) if a in weights and b in weights}
    return res


def smoke_and_project(repo_root, base_cfg, out, args):
    """One check for the whole data -> loss -> image chain, plus a measured-speed time budget.

    Reads real batches through the dataset and DataLoader, runs a forward+backward of the ORIGINAL loss
    (vgg included) on every path from identical weights, times a few steps and one no-grad loss pass, and saves
    one reconstruction grid from an untrained model. Then projects the wall time of the full comparison
    from the measured numbers.
    """
    import lpwm_stn
    from build_model import build
    from datasets.get_dataset import get_image_dataset
    from utils.loss_functions import LossLPIPS
    B, seed = base_cfg["batch_size"], args.seed
    report = {"batch_size": B}
    ds_tr = get_image_dataset(base_cfg["ds"], base_cfg["root"], mode="train", image_size=base_cfg["image_size"])
    ds_va = get_image_dataset(base_cfg["ds"], base_cfg["root"], mode="valid", image_size=base_cfg["image_size"])
    s0 = ds_tr[0][0]
    report["data"] = {"train_items": len(ds_tr), "val_items": len(ds_va), "sample_shape": list(s0.shape), "dtype": str(s0.dtype),
                      "min": float(s0.min()), "max": float(s0.max())}
    gen = torch.Generator().manual_seed(seed)
    loader = torch.utils.data.DataLoader(ds_tr, shuffle=True, batch_size=B, num_workers=4, pin_memory=True, drop_last=True, generator=gen)
    t_prev, gaps, batches = time.perf_counter(), [], []
    for i, batch in enumerate(loader):
        now = time.perf_counter()
        gaps.append(now - t_prev)
        t_prev = now
        if i < 4:
            batches.append(batch[0])
        if i == 59:
            break
    report["dataloader"] = {"batches": len(gaps), "ms_per_batch_after_first_10": 1000 * sum(gaps[10:]) / len(gaps[10:]),
                            "batch_shape": list(batches[0].shape), "range": [float(batches[0].min()), float(batches[0].max())]}
    x = batches[0].cuda()
    recon_loss_func = LossLPIPS(normalized_rgb=base_cfg["normalize_rgb"]).to("cuda")
    kw = dict(warmup=True, with_loss=True, return_alpha_masks=False, beta_kl=base_cfg["beta_kl"], beta_rec=base_cfg["beta_rec"],
              kl_balance=base_cfg["kl_balance"], recon_loss_type=base_cfg["recon_loss_type"], recon_loss_func=recon_loss_func,
              beta_obj=base_cfg.get("beta_obj", 0.0))
    report["paths"] = {}
    x_val, _ = fixed_validation_batch(ds_va, B)
    x_val = x_val.cuda()
    for path in PATHS:
        cfg = dict(base_cfg)
        cfg.update(PATHS[path])
        cfg_path = os.path.join(out, f"smoke_cfg_{path}.json")
        json.dump(cfg, open(cfg_path, "w"))
        torch.manual_seed(seed)
        torch.cuda.manual_seed_all(seed)
        model, _, _ = build(cfg_path, "cuda")
        lpwm_stn.set_backend(PATHS[path]["stn_backend"])
        model.train()
        torch.manual_seed(seed)
        loss = model(x.unsqueeze(1) if x.dim() == 4 else x, **kw)["loss_dict"]["loss"]
        first = float(loss)
        loss.backward()
        opt = torch.optim.Adam(model.parameters(), lr=cfg["lr"])
        ev = []
        torch.cuda.reset_peak_memory_stats()
        for i in range(20):
            opt.zero_grad(set_to_none=True)
            e0, e1 = torch.cuda.Event(enable_timing=True), torch.cuda.Event(enable_timing=True)
            e0.record()
            out_ = model(x.unsqueeze(1) if x.dim() == 4 else x, **kw)
            out_["loss_dict"]["loss"].backward()
            opt.step()
            e1.record()
            torch.cuda.synchronize()
            if i >= 5:
                ev.append(e0.elapsed_time(e1))
        peak = torch.cuda.max_memory_allocated() / 1e6
        vf = []
        for i in range(6):
            model.eval()
            e0, e1 = torch.cuda.Event(enable_timing=True), torch.cuda.Event(enable_timing=True)
            with torch.no_grad():
                e0.record()
                model(x_val.unsqueeze(1), **{**kw, "warmup": False})
                e1.record()
            torch.cuda.synchronize()
            if i >= 1:
                vf.append(e0.elapsed_time(e1))
        report["paths"][path] = {"first_step_loss": first, "fused_composite_calls": model.decoder_module.fused_composite_calls,
                                 "step_ms_cuda_events": sorted(ev)[len(ev) // 2], "peak_alloc_mb": peak,
                                 "val_forward_ms": sum(vf) / len(vf), "loss_finite": bool(torch.isfinite(loss))}
        if path == "reference":
            rec = reconstruct(model, x_val)     # after 21 optimizer steps on one batch: this only exercises the image path
            save_grid([x_val, rec], os.path.join(out, "smoke_reconstructions.png"), nrow=B)
            report["image_saved"] = {"path": os.path.join(out, "smoke_reconstructions.png"), "input_shape": list(x_val.shape), "rec_shape": list(rec.shape)}
        del model, opt
        torch.cuda.empty_cache()
    # projection from measured speed (never from the earlier 3-9 min/epoch guess)
    steps = len(ds_tr) // B
    val_batches = -(-len(ds_va) // B)
    overhead_ms = 1.5           # measured on shapes: wall per iteration - CUDA-event step
    per_run = {}
    for path, r in report["paths"].items():
        step_wall = max(r["step_ms_cuda_events"] + overhead_ms, report["dataloader"]["ms_per_batch_after_first_10"])
        epoch_s = steps * step_wall / 1000 + val_batches * r["val_forward_ms"] / 1000 + 12
        per_run[path] = {"step_wall_ms": step_wall, "epoch_s": epoch_s, "run_s": 20 + args.epochs * epoch_s + 45}
    total = 2 * sum(v["run_s"] for v in per_run.values())
    report["projection"] = {"steps_per_epoch": steps, "val_batches": val_batches, "per_run": per_run, "runs": 6, "epochs_total": 6 * args.epochs,
                            "total_s_no_margin": total, "total_s_with_20pct_margin": 1.2 * total, "budget_s": args.budget_seconds,
                            "within_budget": 1.2 * total <= args.budget_seconds}
    json.dump(report, open(os.path.join(out, "smoke_and_projection.json"), "w"), indent=2)
    print(json.dumps(report, indent=1), flush=True)
    return report


def summarize(report):
    runs = report["runs"]
    by = {(r["path"], r["tag"]): r for r in runs}
    print("\n=== identical starting point across paths (pass 1)")
    for key in ("startup.init_weights_sha256", "first_step.first_batch_sha256", "first_step.first_step_loss"):
        a, b = key.split(".")
        print(f"  {key}: " + " | ".join(f"{p}={by[(p, '_p1')].get(a, {}).get(b)}" for p in PATHS))
    print("  path check: " + " | ".join(f"{p}: backend={by[(p, '_p1')]['first_step']['backend']} fused_calls_first_step={by[(p, '_p1')]['first_step']['fused_composite_calls']}" for p in PATHS))
    n_ep = len(by[("reference", "_p1")]["epochs"])
    for metric, label in (("train_loss", "train loss"), ("psnr", "train PSNR dB"), ("median_ms", "step median ms (CUDA events)"), ("peak_alloc_mb", "peak allocated MB"), ("epoch_wall_s", "epoch wall s")):
        print(f"\n=== {label}   (rows: path/pass; columns: epoch)")
        for r in runs:
            print("  %-12s " % (r["path"] + r["tag"]) + "  ".join("%12.4f" % e[metric] for e in r["epochs"]))
    print("\n=== validation loss per epoch")
    for r in runs:
        print("  %-12s " % (r["path"] + r["tag"]) + "  ".join("%12.3f" % v for v in r["validation_loss"]))
    print("\n=== trajectory divergence of train loss (max relative over epochs), cross-path vs same-path run-to-run")
    def dev(a, b):
        return max(abs(x["train_loss"] - y["train_loss"]) / abs(y["train_loss"]) for x, y in zip(a["epochs"], b["epochs"]))
    for a, b in (("triton", "reference"), ("fused", "reference"), ("fused", "triton")):
        print(f"  {a} vs {b} (pass 1): {dev(by[(a, '_p1')], by[(b, '_p1')]):.2e}")
    for p in PATHS:
        print(f"  {p} pass1 vs pass2 (same path): {dev(by[(p, '_p1')], by[(p, '_p2')]):.2e}")
    print("\n=== reconstruction (final checkpoints, evaluated on the reference path)")
    rc = report["reconstruction"]
    for key, v in rc["runs"].items():
        print("  %-14s fixed batch MSE %.3e PSNR %.2f dB | whole validation set (%d images) MSE %.3e PSNR %.2f dB" % (
            key, v["fixed_batch"]["mse"], v["fixed_batch"]["psnr_db"], v["full_validation_set"]["images"], v["full_validation_set"]["mse"], v["full_validation_set"]["psnr_db"]))
    print("  final-weight relative L2 between models:", json.dumps(rc["weight_relative_l2_between_final_models"]))


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--repo-root", required=True)
    ap.add_argument("--config", required=True)
    ap.add_argument("--epochs", type=int, default=3)
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--recon-images", type=int, default=16)
    ap.add_argument("--set", nargs="*", default=[], help="extra config overrides, key=json_value (e.g. batch_size=16)")
    ap.add_argument("--smoke-first", action="store_true", help="run the data/VGG/image smoke check and the measured time projection first; stop if it fails or exceeds the budget")
    ap.add_argument("--smoke-only", action="store_true")
    ap.add_argument("--budget-seconds", type=float, default=6000.0)
    ap.add_argument("--lpips-head", default=None, help="path to vgg.pth; copied to eval/lpips/ under --out so training never downloads it")
    ap.add_argument("--from-runs", default=None, help="skip training: reuse the runs recorded in this train_runs.json")
    ap.add_argument("--out", required=True)
    args = ap.parse_args(argv)
    args.set = {k: json.loads(v) for k, v in (s.split("=", 1) for s in args.set)}

    repo_root = be._bootstrap(args.repo_root)
    config = args.config if os.path.isabs(args.config) else os.path.join(repo_root, args.config)
    out = os.path.abspath(args.out)
    os.makedirs(out, exist_ok=True)
    base_cfg = json.load(open(config))
    base_cfg.update(args.set)
    os.chdir(out)                                   # train_dlp.py writes its run directories to the cwd
    if args.lpips_head:
        os.makedirs("eval/lpips", exist_ok=True)
        shutil.copy(args.lpips_head, "eval/lpips/vgg.pth")
    if base_cfg["ds"] == "shapes":
        patch_shapes_dataset(args.seed)
    if args.smoke_first or args.smoke_only:
        smoke = smoke_and_project(repo_root, base_cfg, out, args)
        if args.smoke_only:
            return 0
        bad = [p for p, r in smoke["paths"].items() if not r["loss_finite"]]
        equal = len({round(r["first_step_loss"], 3) for r in smoke["paths"].values()}) == 1
        if bad or not smoke["projection"]["within_budget"]:
            print(f"STOPPED before training: non-finite={bad}, within_budget={smoke['projection']['within_budget']}, "
                  f"projected={smoke['projection']['total_s_with_20pct_margin']:.0f}s vs budget {args.budget_seconds:.0f}s", flush=True)
            return 3
        print(f"smoke ok; first-step losses equal across paths (3 decimals): {equal}; projected {smoke['projection']['total_s_with_20pct_margin']:.0f}s within budget", flush=True)
    if args.from_runs:
        runs = [{**r, **parse_log(r["log_dir"])} for r in json.load(open(args.from_runs))]   # re-read the logs
    else:
        runs = []
        for i, order in enumerate(ORDERS, 1):
            for path in order:
                runs.append(train_one(repo_root, base_cfg, path, f"_p{i}", out, args))
                json.dump(runs, open(os.path.join(out, "train_runs.json"), "w"), indent=2)   # kept even if a later step fails
    report = {"kind": "short single-GPU training comparison through train_dlp.py; not convergence, not quality",
              "dataset": base_cfg["ds"], "synthetic_procedural_dataset": base_cfg["ds"] == "shapes",
              "recon_loss_type": base_cfg.get("recon_loss_type"), "epochs": args.epochs, "seed": args.seed,
              "host": socket.gethostname(), "slurm_job_id": os.environ.get("SLURM_JOB_ID"),
              "date_utc": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()), "env": be.env_record(),
              "repo": be.repo_record(repo_root), "config": config, "config_sha256": be.file_sha256(config),
              "script_sha256": be.file_sha256(os.path.abspath(__file__)), "command": sys.argv, "runs": runs}
    report["reconstruction"] = reconstruction_check(repo_root, base_cfg, runs, out, args)
    json.dump(report, open(os.path.join(out, "train_compare.json"), "w"), indent=2)
    summarize(report)
    print("\nwrote", os.path.join(out, "train_compare.json"))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
